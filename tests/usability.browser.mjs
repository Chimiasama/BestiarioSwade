import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
const base = process.env.APP_URL || 'http://127.0.0.1:3000';
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base);
  await page.getByRole('searchbox', { name: 'Buscar em todos os livros' }).fill('arvore animada');
  await page.getByRole('button', { name: 'Buscar criaturas', exact: true }).click();
  await page.getByRole('heading', { name: 'Árvore Animada', exact: true }).waitFor();
  assert.equal(await page.locator('[role="article"]').count(), 1, 'accent-insensitive name search must not match mentions in unrelated lore');
  await page.getByTitle('Limpar busca').click();
  assert.equal(await page.locator('[role="article"]').count(), 40);
  await page.getByRole('button', { name: 'Próxima', exact: true }).click();
  await page.getByText('Mostrando 41–80 de 1126', { exact: true }).waitFor();
  assert.equal(await page.locator('[role="article"]').count(), 40);
  await page.getByRole('button', { name: 'Filtros', exact: true }).click();
  await page.getByLabel('Filtrar por cenário').selectOption({ label: 'Havenwood' });
  await page.locator('button[aria-controls="advanced-filters"]').click();
  await page.getByRole('heading', { name: 'Árvore Animada', exact: true }).waitFor();
  const resultRows = await page.locator('[role="article"]').count();
  assert.ok(resultRows < 40);
  await page.getByRole('button', { name: 'Limpar filtros', exact: true }).click();
  await page.getByRole('button', { name: 'Próxima', exact: true }).click();
  await page.getByText('Mostrando 41–80 de 1126', { exact: true }).waitFor();
  await page.evaluate(() => window.scrollTo(0, 1200));
  const listY = await page.evaluate(() => window.scrollY);
  const viewedName = await page.locator('[role="article"]').nth(15).getByRole('heading').innerText();
  await page.locator('[role="article"]').nth(15).getByRole('button', { name: /^Abrir ficha/ }).click();
  assert.equal(await page.evaluate(() => window.scrollY), 0, 'new details should open at the top');
  await page.getByRole('button', { name: 'Voltar ao Compêndio' }).click();
  await page.getByText('Mostrando 41–80 de 1126', { exact: true }).waitFor();
  assert.ok(await page.evaluate(() => window.scrollY) > 500, 'return must preserve list reading position');
  assert.ok(listY > 500);
  await page.getByRole('button', { name: 'Por Cenários', exact: true }).click();
  await page.getByRole('heading', { name: 'Consultados recentemente' }).waitFor();
  await page.locator('.home-search').getByRole('button', { name: viewedName, exact: true }).waitFor();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.getByRole('button', { name: 'Criar', exact: true }).click();
  const name = page.getByLabel('Nome do monstro', { exact: true });
  await name.fill('Criatura de teste UX');
  const save = page.getByRole('button', { name: 'Salvar criatura', exact: true });
  assert.equal(await save.isEnabled(), true);
  const saveBounds = await save.boundingBox();
  assert.ok(saveBounds && saveBounds.y > 0 && saveBounds.y + saveBounds.height <= 844, 'save stays in reach on mobile');
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
  await page.getByRole('alertdialog', { name: 'Descartar alterações?' }).waitFor();
  await page.getByRole('alertdialog').getByRole('button', { name: 'Cancelar', exact: true }).click();
  assert.equal(await name.inputValue(), 'Criatura de teste UX');
  await page.evaluate(() => {
    window.originalStorageWrite = Storage.prototype.setItem;
    Storage.prototype.setItem = function () { throw new DOMException('Quota exceeded', 'QuotaExceededError'); };
  });
  await save.click();
  await page.getByRole('alert').filter({ hasText: 'Não foi possível salvar' }).waitFor();
  assert.equal(await name.inputValue(), 'Criatura de teste UX');
  await page.evaluate(() => { Storage.prototype.setItem = window.originalStorageWrite; });
  await save.click();
  await page.getByRole('searchbox', { name: 'Buscar em todos os livros' }).waitFor();
  await page.getByRole('searchbox', { name: 'Buscar em todos os livros' }).fill('Criatura de teste UX');
  await page.getByRole('button', { name: 'Buscar criaturas', exact: true }).click();
  await page.getByRole('heading', { name: 'Criatura de teste UX', exact: true }).waitFor();
  await page.getByRole('heading', { name: 'Criatura de teste UX', exact: true }).click();
  await page.locator('.detail-actions summary').click();
  await page.getByRole('button', { name: 'Excluir criatura', exact: true }).click();
  await page.getByRole('alertdialog', { name: 'Excluir criatura?' }).getByRole('button', { name: 'Cancelar' }).click();
  await page.getByRole('heading', { name: 'Criatura de teste UX', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Menu de ferramentas' }).click();
  await page.getByRole('button', { name: 'Mudar Tema, Cores e Fontes do Grimório' }).click();
  const appearance = page.getByRole('dialog', { name: 'Aparência do Grimório' });
  await appearance.getByRole('button', { name: /Noturno/ }).first().click();
  assert.equal(await page.getByLabel('Seguir aparência do sistema').isChecked(), false);
  const theme = await page.locator('html').getAttribute('data-theme');
  await page.keyboard.press('Escape');
  await appearance.waitFor({ state: 'hidden' });
  await page.reload();
  assert.equal(await page.locator('html').getAttribute('data-theme'), theme, 'manual theme persists across reload');
  for (const width of [320, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    await page.goto(base);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `home overflow at ${width}px`);
    await page.getByRole('button', { name: /Todos|Compêndio Geral/ }).click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `catalog overflow at ${width}px`);
    assert.ok(await page.locator('*').count() < 3500, 'catalog rendering stays bounded');
  }
  assert.deepEqual(errors, []);
  console.log('PASS: accent search, pagination, filters, reading position, recent items, mobile save, discard safety, quota failure/retry, deletion cancel, theme persistence, and 320/390/768/1440px layouts.');
} finally { await browser.close(); }
