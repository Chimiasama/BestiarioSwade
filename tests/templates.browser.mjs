 assert.match(await page.getByLabel('Poderes e Pontos de Poder').inputValue(),/30 Pontos de Poder/);
 assert.equal(await page.getByRole('checkbox',{name:'Carta Selvagem (Wild Card)'}).isChecked(),true);
 await page.getByRole('button',{name:'Salvar criatura',exact:true}).click();
