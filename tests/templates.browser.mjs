 await library.getByRole('article',{name:'Prévia do modelo'}).getByText('Arquimago',{exact:true}).waitFor();
 await page.screenshot({path:'/tmp/template-library-mobile.png'});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await library.getByRole('button',{name:'Usar modelo: Arquimago',exact:true}).click();
 await page.getByRole('alertdialog',{name:'Aplicar modelo de criatura?'}).getByRole('button',{name:'Cancelar',exact:true}).click();
 assert.equal(await page.getByLabel('Título ou arquétipo',{exact:true}).inputValue(),'Soldado');
 await page.getByRole('button',{name:/Explorar 79 modelos/}).click();
 await library.getByRole('button',{name:'Usar modelo: Arquimago',exact:true}).click();
 await page.getByRole('button',{name:'Aplicar modelo',exact:true}).click();
